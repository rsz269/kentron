"""
Bicycle - Main Assembly
Generated by @cad: "Create a bicycle with frame, wheels, seat, and handlebars"

This example demonstrates:
- Assembly-first project structure (assembly.py + parts/ folder)
- Multi-part assembly with color coding
- CadQuery Assembly constraints
"""
import cadquery as cq
from config import COLORS
from parts.frame import build as make_frame
from parts.wheel import build as make_wheel
from parts.seat import build as make_seat
from parts.handlebars import build as make_handlebars


def build():
    """Build the complete bicycle assembly."""
    assy = cq.Assembly(name="bicycle")
    
    # ─── Add Frame ──────────────────────────────────────────────
    assy.add(
        make_frame(), 
        name="frame", 
        color=cq.Color(*COLORS['structural'])
    )
    
    # ─── Add Rear Wheel ─────────────────────────────────────────
    assy.add(
        make_wheel(), 
        name="rear_wheel",
        color=cq.Color(*COLORS['moving']),
        loc=cq.Location((-400, 0, 0))
    )
    
    # ─── Add Front Wheel ────────────────────────────────────────
    assy.add(
        make_wheel(), 
        name="front_wheel",
        color=cq.Color(*COLORS['moving']),
        loc=cq.Location((500, 0, 0))
    )
    
    # ─── Add Seat ───────────────────────────────────────────────
    assy.add(
        make_seat(),
        name="seat",
        color=cq.Color(*COLORS['accent']),
        loc=cq.Location((0, 0, 520))
    )
    
    # ─── Add Handlebars ─────────────────────────────────────────
    assy.add(
        make_handlebars(),
        name="handlebars",
        color=cq.Color(*COLORS['chrome']),
        loc=cq.Location((480, 0, 480), (0, -15, 0))
    )
    
    # ─── Solve (only if constraints defined) ────────────────────
    if assy.constraints:
        assy.solve()
    
    return assy


# ─── Standalone Preview ─────────────────────────────────────────
result = build()
