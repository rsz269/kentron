"""
Bicycle Handlebars - Drop-style handlebars with stem
Generated by @cad: "Create bicycle handlebars"
"""
import cadquery as cq

def build():
    """Build simplified drop handlebars with stem."""
    
    bar_radius = 12
    bar_width = 420  # total width
    stem_length = 100
    drop = 130
    
    # Stem (connects to fork)
    stem = (
        cq.Workplane("XZ")
        .circle(bar_radius)
        .extrude(stem_length)
    )
    
    # Cross bar (horizontal)
    cross_bar = (
        cq.Workplane("YZ")
        .center(-bar_width / 2, 0)
        .circle(bar_radius)
        .extrude(bar_width)
        .translate((stem_length, 0, 0))
    )
    
    # Grip ends (slight drop)
    grip_r = (
        cq.Workplane("XZ")
        .center(stem_length, 0)
        .transformed(offset=(0, bar_width / 2, 0))
        .circle(bar_radius)
        .extrude(-drop)
    )
    grip_l = (
        cq.Workplane("XZ")
        .center(stem_length, 0)
        .transformed(offset=(0, -bar_width / 2, 0))
        .circle(bar_radius)
        .extrude(-drop)
    )
    
    handlebar = stem.union(cross_bar).union(grip_r).union(grip_l)
    handlebar.faces("<X").tag("stem_mount")
    
    return handlebar


# Standalone preview
result = build()
