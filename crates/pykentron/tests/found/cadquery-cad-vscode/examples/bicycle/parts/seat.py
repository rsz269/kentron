"""
Bicycle Seat - Simple saddle shape
Generated by @cad: "Create a bicycle seat"
"""
import cadquery as cq

def build():
    """Build a simplified bicycle seat/saddle."""
    
    # Saddle base - elongated shape
    saddle = (
        cq.Workplane("XY")
        .ellipse(140, 65)
        .extrude(25)
        .edges(">Z").fillet(5)
    )
    
    # Seat post
    post_length = 200
    seat_post = (
        cq.Workplane("XY")
        .center(0, 0)
        .circle(15)
        .extrude(-post_length)
    )
    
    seat = saddle.union(seat_post)
    seat.faces("<Z").tag("mount")
    
    return seat


# Standalone preview
result = build()
