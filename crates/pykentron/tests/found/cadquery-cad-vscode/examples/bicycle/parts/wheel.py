import cadquery as cq

def build(radius=340, width=25):
    """Build a simplified bicycle wheel (rim + hub + spokes)."""
    
    rim_thickness = 8
    hub_radius = 25
    hub_width = 40
    spoke_radius = 1.5
    num_spokes = 16
    
    # Rim (torus-like ring)
    rim = (
        cq.Workplane("XY")
        .circle(radius).circle(radius - rim_thickness)
        .extrude(width)
        .translate((0, 0, -width / 2))
    )
    
    # Hub (central cylinder)
    hub = (
        cq.Workplane("XY")
        .circle(hub_radius)
        .extrude(hub_width)
        .translate((0, 0, -hub_width / 2))
    )
    
    # Spokes (radial cylinders)
    spoke_length = radius - rim_thickness - hub_radius
    spokes = cq.Workplane("XY")
    
    for i in range(num_spokes):
        angle = i * (360 / num_spokes)
        spoke = (
            cq.Workplane("XZ")
            .center(hub_radius, 0)
            .circle(spoke_radius)
            .extrude(spoke_length)
            .rotate((0, 0, 0), (0, 0, 1), angle)
        )
        if i == 0:
            spokes = spoke
        else:
            spokes = spokes.union(spoke)
    
    # Tire (outer ring)
    tire_thickness = 15
    tire = (
        cq.Workplane("XY")
        .circle(radius + tire_thickness).circle(radius)
        .extrude(width + 4)
        .translate((0, 0, -(width + 4) / 2))
    )
    
    wheel = rim.union(hub).union(spokes).union(tire)
    
    # Tags for assembly
    wheel.faces(">Z").tag("side_right")
    wheel.faces("<Z").tag("side_left")
    
    return wheel


