/// The constant-binormal frame keeps `T × N = D` with `T` leaning the spine's way; along a
/// helix about its axis `D`, `T` is level and `N` is `D × T`.
#[test]
fn a_constant_binormal_frame_keeps_its_binormal() {
    let helix = super::super::corrected::tests::helix(2.0, 0.6, 1.5, 90);
    let Curve::BSpline(h) = &helix else { unreachable!() };
    let d = Vector::new(0.0, 0.0, 1.0);
    for (curve, first, last, binormal) in [(&helix, h.first_parameter(), h.last_parameter(), d), (&twisted_s(), 3.0, 0.0, Vector::new(0.3, 0.2, 1.0))] {
        let law = ConstantBinormalLaw::new(curve, first, last, binormal);
        let frenet = FrenetLaw::new(curve, first, last);
        let unit_d = unit(binormal);
        for i in 0..=40 {
            let f = i as f64 / 40.0;
            let (t, n) = law.at_fraction(f);
            assert!((t.cross(n) - unit_d).length() < 1e-12, "at {f}");
            assert!(t.dot(frenet.at_fraction(f).0) > 0.0);
            if binormal == d {
                assert!(t.z.abs() < 1e-12 && (n - d.cross(t)).length() < 1e-12);
            }
        }
    }
}

/// The discrete frame: constant along a straight B-spline; along a planar curve its third
/// axis `T × N` keeps its angle to the plane's normal (along a curve in the XY plane, it is
/// ±Z); at its samples (ten per knot span) it is the
/// rotation-method transport of the default normal, turned here by an independent
/// matrix form of the least rotation.
#[test]
fn the_discrete_frame_is_the_rotation_method_frame() {
    let straight = cubic(vec![p(1.0, 1.0, 1.0), p(2.0, 3.0, 4.0), p(3.0, 5.0, 7.0), p(4.0, 7.0, 10.0), p(6.0, 11.0, 16.0)], vec![0.0, 0.5, 2.0], vec![4, 1, 4]);
    let law = DiscreteLaw::new(&straight, 0.0, 2.0).unwrap();
    let (t0, n0) = law.at_fraction(0.0);
    for i in 0..=20 {
        let (t, n) = law.at_fraction(i as f64 / 20.0);
        assert!((t - t0).length() < 1e-12 && (n - n0).length() < 1e-12);
    }
    let tilt = Transform::rotation(Axis::new(Point::ORIGIN, Direction::from_vector(Vector::new(1.0, -2.0, 0.5))), 0.9);
    let s = planar_s().transformed(&tilt);
    let plane_normal = Vector::new(0.0, 0.0, 1.0).transformed(&tilt);
    let law = DiscreteLaw::new(&s, 3.0, 0.0).unwrap();
    let (t0, n0) = law.at_fraction(0.0);
    let lean = t0.cross(n0).dot(plane_normal);
    for i in 0..=30 {
        let (t, n) = law.at_fraction(i as f64 / 30.0);
        assert!((t.cross(n).dot(plane_normal) - lean).abs() < 1e-12);
    }
    let law = DiscreteLaw::new(&planar_s(), 3.0, 0.0).unwrap();
    for i in 0..=30 {
        let (t, n) = law.at_fraction(i as f64 / 30.0);
        assert!(t.cross(n).cross(Vector::new(0.0, 0.0, 1.0)).length() < 1e-12);
    }
    // (At the samples, against a transport written out here.)
    let curve = twisted_s();
    let law = DiscreteLaw::new(&curve, 0.0, 3.0).unwrap();
    let tangent = |u: f64| unit(curve.d1(u).1);
    let turn = |x: Vector, a: Vector, b: Vector| -> Vector {
        // (R = I + [k]× + [k]×²/(1 + c), k = a × b, c = a·b.)
        let k = a.cross(b);
        let c = a.dot(b);
        let kx = k.cross(x);
        let r = x + kx + k.cross(kx) * (1.0 / (1.0 + c));
        unit(b.cross(r.cross(b)))
    };
    let t = tangent(0.0);
    let mut x = Vector::from(Frame::from_z(Point::ORIGIN, Direction::from_vector(t)).x());
    let mut previous = t;
    for k in 0..=30 {
        let u = 0.1 * k as f64;
        let t = tangent(u);
        if k > 0 {
            x = turn(x, previous, t);
        }
        previous = t;
        let (lt, ln) = law.at_fraction(u / 3.0);
        assert!((lt - t).length() < 1e-12 && (ln - x).length() < 1e-9, "at {u}: {ln:?} vs {x:?}");
    }
}
