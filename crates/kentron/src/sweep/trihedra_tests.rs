fn p(x: f64, y: f64, z: f64) -> Point {
    Point::new(x, y, z)
}

fn cubic(poles: Vec<Point>, knots: Vec<f64>, mults: Vec<usize>) -> Curve {
    Curve::BSpline(BSplineCurve::new(poles, knots, mults, 3))
}

fn planar_s() -> Curve {
    cubic(vec![p(0.0, 0.0, 0.0), p(1.0, 2.0, 0.0), p(2.0, 2.0, 0.0), p(3.0, -2.0, 0.0), p(4.0, -2.0, 0.0), p(5.0, 0.0, 0.0)], vec![0.0, 1.0, 2.0, 3.0], vec![4, 1, 1, 4])
}

fn twisted_s() -> Curve {
    cubic(vec![p(0.0, 0.0, 0.0), p(1.0, 2.0, 0.5), p(2.0, 2.0, 1.0), p(3.0, -2.0, 1.5), p(4.0, -2.0, 2.0), p(5.0, 0.0, 2.5)], vec![0.0, 1.0, 2.0, 3.0], vec![4, 1, 1, 4])
}

